package TimeAndSpaceComplexities;

public class TimeComplexity7 {
    public static void main(String[] args) {
        int n = 56;
        int m = 56;
        for(int i=1;i<=m;i++){
            for(int j=0;j<=n;j++){
                System.out.println("Gawade");
            }
        }
    }
}

//total operations = m*n
//time complexity = O(m*n)