package TimeAndSpaceComplexities;

public class TimeComplexity6 {
    public static void main(String[] args) {
        //O(n) and o(m+n) etc are called liner time
        //O(1) is called constant time
        int n = 56;
        for(int i=-8;i<=n+5;i+=3){
            System.out.println("Natasha");
        }
    }
}
//total operations = constant
//Time complexity = O(1)