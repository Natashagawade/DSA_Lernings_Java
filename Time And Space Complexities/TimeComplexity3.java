package TimeAndSpaceComplexities;

public class TimeComplexity3 {
    public static void main(String[] args) {
        int n = 56;
        for(int i=1;i<=n;i++){
            System.out.println("Natasha");
        }
        for(int i=0;i<=n;i++){
            System.out.println("Gawade");
        }
    }
}

//total operations = n+n = 2n
//time complexity = O(2n) = O(n)