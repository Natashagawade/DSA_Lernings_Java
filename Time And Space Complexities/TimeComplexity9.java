package TimeAndSpaceComplexities;

public class TimeComplexity9 {
    public static void main(String[] args) {
        int n = 56;
        for(int i=1;i<=n;i++){
            for(int j=1;j<=i;j++){
                System.out.println("Natasha");
            }
        }
    }
}

//Total operations = n(n+1)/2
//time complexity = O(n^2)