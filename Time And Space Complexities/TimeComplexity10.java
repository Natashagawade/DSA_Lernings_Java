package TimeAndSpaceComplexities;

public class TimeComplexity10 {
    public static void main(String[] args) {
        int n =345;
        for(int i=1;i<=n;i*=2){
            System.out.println("Natasha");
        }
    }
}

//total no of operations=log2n-1
//time complexity = O(log2n-1)