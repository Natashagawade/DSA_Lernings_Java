package TimeAndSpaceComplexities;

public class TimeComplexity8 {
    public static void main(String[] args) {
        int n = 56;
        for(int i=1;i<=n;i++){
            for(int j=0;j<=n;j++){
                System.out.println("Gawade");
            }
        }
    }
}

//time complexity = O(n*n) = O(n^2)