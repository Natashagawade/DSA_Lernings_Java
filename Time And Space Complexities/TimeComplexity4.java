package TimeAndSpaceComplexities;

public class TimeComplexity4 {
    public static void main(String[] args) {
        int n = 56;
        int m = 34;
        for(int i=1;i<=n;i++){
            System.out.println("Natasha");
        }
        for(int i=0;i<=m;i++){
            System.out.println("Gawade");
        }
    }
}

//total operations = n+m
//time complexity = O(m+n)